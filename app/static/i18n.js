function detectUiLang() {
  const q = new URLSearchParams(location.search).get("lang");
  if (q && UI_LANGS.includes(q)) return q;
  try {
    const saved = localStorage.getItem("ui_lang");
    if (saved && UI_LANGS.includes(saved)) return saved;
  } catch (err) { /* ignore */ }
  const list = [...(navigator.languages || []), navigator.language || ""];
  for (const raw of list) {
    const tag = String(raw || "").toLowerCase().replace("_", "-");
    if (tag.startsWith("zh")) return "zh";
    if (tag.startsWith("ja")) return "ja";
    if (tag.startsWith("fr")) return "fr";
    if (tag.startsWith("en")) return "en";
  }
  return "zh";
}

const UI_LANG = detectUiLang();

function t(key, vars) {
  const table = I18N[UI_LANG] || I18N.zh;
  let s = table[key] || I18N.zh[key] || key;
  if (vars) {
    Object.keys(vars).forEach((name) => {
      s = s.replaceAll("{" + name + "}", String(vars[name]));
    });
  }
  return s;
}

function sceneLabel(scene) {
  const id = scene && scene.id ? scene.id : scene;
  const key = "scene_" + id;
  if ((I18N[UI_LANG] && I18N[UI_LANG][key]) || I18N.zh[key]) return t(key);
  return (scene && scene.label_zh) || id || "";
}

function packLabel(id) {
  const key = "pack_" + id;
  if ((I18N[UI_LANG] && I18N[UI_LANG][key]) || I18N.zh[key]) return t(key);
  return id || "";
}

function localizeLangList(raw) {
  const map = {
    "中文": t("name_zh"),
    "英文": t("name_en"),
    "日文": t("name_ja"),
    "法文": t("name_fr"),
    "西班牙文": t("name_es"),
    "韩文": t("name_ko"),
    "泰文": t("name_th"),
  };
  return String(raw || "").split("、").map((part) => map[part] || part).join("、");
}

function localizeServerMessage(msg) {
  const s = String(msg || "");
  const exact = {
    "正在准备图片…": "srv_prep",
    "正在识读题刻文字…": "srv_ocr",
    "正在观察画面，生成待核验候选…": "srv_watch",
    "正在调用阿里云搜索，对照画面特征核验候选…": "srv_search",
    "正在准备术语表…": "srv_terms",
    "正在生成中文，完成后并发翻译其它语言…": "srv_write",
    "正在生成其余语种，已完成的内容可先阅读": "srv_partial",
    "部分语种生成失败，已保留其它内容": "srv_partial_fail",
    "讲解完成": "done",
    "正在处理": "processing",
    "请上传 jpg / png / webp 图片": "err_type",
    "图片是空的": "err_empty",
    "图片请小于 10MB": "err_size",
  };
  if (exact[s]) return t(exact[s]);
  let m = s.match(/^正在处理图片（(\d+) KB）$/);
  if (m) return t("srv_kb", { kb: m[1] });
  m = s.match(/^按(.+)范围识别…$/);
  if (m) return t("srv_scope", { city: m[1] });
  m = s.match(/^(.+)（本阶段已等待 (\d+) 秒）$/);
  if (m) return t("srv_wait", { msg: localizeServerMessage(m[1]), n: m[2] });
  m = s.match(/^初步判断：(.+)$/);
  if (m) return t("srv_guess", { name: m[1] });
  m = s.match(/^核验结果：(.+)$/);
  if (m) {
    const inner = m[1]
      .replace("证据较充分", t("decision_confirmed"))
      .replace("较可能，仍需核实", t("decision_probable"))
      .replace("待核验候选", t("decision_possible"))
      .replace("无法确认", t("decision_unknown"));
    return t("srv_verify", { name: inner });
  }
  m = s.match(/^已写出(.+)$/);
  if (m) return t("srv_wrote", { names: localizeLangList(m[1]) });
  m = s.match(/^(.+)生成失败，其它语种继续$/);
  if (m) return t("srv_lang_fail", { names: localizeLangList(m[1]) });
  return s;
}

function reorderLangPanels() {
  const box = document.getElementById("langs");
  if (!box) return;
  const order = [UI_LANG, "zh", "en", "ja", "fr", "es", "ko", "th"].filter((id, i, arr) => arr.indexOf(id) === i);
  order.forEach((id) => {
    const node = document.getElementById(id);
    if (node && node.parentElement) box.appendChild(node.parentElement);
  });
}

function applyI18n() {
  document.documentElement.lang = { zh: "zh-CN", en: "en", ja: "ja", fr: "fr" }[UI_LANG] || "zh-CN";
  document.title = t("title");
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.getAttribute("data-i18n-html"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    el.alt = t(el.getAttribute("data-i18n-alt"));
  });
  document.querySelectorAll(".lang-switch [data-lang]").forEach((btn) => {
    btn.classList.toggle("on", btn.getAttribute("data-lang") === UI_LANG);
  });
  const nav = document.querySelector(".lang-switch");
  if (nav) nav.setAttribute("aria-label", t("lang_switch"));
  reorderLangPanels();
}

function bindLangSwitch() {
  const nav = document.querySelector(".lang-switch");
  if (!nav) return;
  nav.addEventListener("click", (ev) => {
    const btn = ev.target.closest("[data-lang]");
    if (!btn) return;
    const lang = btn.getAttribute("data-lang");
    if (!UI_LANGS.includes(lang) || lang === UI_LANG) return;
    try { localStorage.setItem("ui_lang", lang); } catch (err) { /* ignore */ }
    const url = new URL(location.href);
    url.searchParams.set("lang", lang);
    location.assign(url.pathname + url.search + url.hash);
  });
}

applyI18n();
bindLangSwitch();
